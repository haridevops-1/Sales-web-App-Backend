#!/usr/bin/env node
"use strict";

// Deploys with every environment value taken from the git-ignored .env, so nothing that
// identifies the project (URLs, IDs, bucket names) or any secret is ever committed.
//
// Catalyst replaces a function's Console variables with its catalyst-config.json on every
// deploy, so the values must be in the config at deploy time. This script:
//   1. checks the repo is clean of secrets and identifiers,
//   2. fills each function's env_variables from .env (list: scripts/function-env.json),
//   3. writes each Slate app's config.js from API_BASE_URL,
//   4. runs `catalyst deploy`,
//   5. restores every config file to its committed (value-free) text - even on failure or Ctrl-C.
//
//   node scripts/deploy.js [--only functions,apig,slate]

const { spawnSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const MANIFEST = JSON.parse(fs.readFileSync(path.join(__dirname, "function-env.json"), "utf8"));
const SLATE_APPS = ["spikra-experience", "spikra-w2-proposal"];
// workdrive-auth keeps its own state-signing secret, separate from app-auth's.
const OVERRIDES = { "workdrive-auth": { STATE_SIGNING_SECRET: "STATE_SIGNING_SECRET_WORKDRIVE_AUTH" } };

function parseEnv(file) {
	const env = {};
	for (const line of fs.readFileSync(file, "utf8").split("\n")) {
		const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
		if (m) env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, "$2");
	}
	return env;
}

function run(cmd, args) {
	const result = spawnSync(cmd, args, { cwd: ROOT, stdio: "inherit" });
	if (result.status !== 0) process.exit(result.status || 1);
}

const envFile = path.join(ROOT, ".env");
if (!fs.existsSync(envFile)) {
	console.error("Missing .env. Copy .env.example to .env and fill it in.");
	process.exit(1);
}
const env = parseEnv(envFile);

// Build every config first; fail before touching any file if a value is missing.
const configs = [];
const missing = [];
for (const [fn, names] of Object.entries(MANIFEST)) {
	const file = path.join(ROOT, "functions", fn, "catalyst-config.json");
	const original = fs.readFileSync(file, "utf8");
	const json = JSON.parse(original);
	json.deployment.env_variables = {};
	for (const name of names) {
		const source = (OVERRIDES[fn] && OVERRIDES[fn][name] && env[OVERRIDES[fn][name]]) ? OVERRIDES[fn][name] : name;
		if (!env[source]) missing.push(`${name} (${fn})`);
		else json.deployment.env_variables[name] = env[source];
	}
	configs.push({ file, original, filled: JSON.stringify(json, null, "\t") + "\n" });
}
if (!env.API_BASE_URL) missing.push("API_BASE_URL (Slate config.js)");
if (missing.length) {
	console.error("These values are empty in .env:\n  " + missing.join("\n  "));
	process.exit(1);
}

run("node", ["scripts/check-secrets.js"]);
run("node", ["scripts/sync-shared.js"]);

const slateConfigs = SLATE_APPS.map((app) => path.join(ROOT, "slate", app, "config.js"));
function restore() {
	for (const { file, original } of configs) fs.writeFileSync(file, original);
}
process.on("SIGINT", () => { restore(); process.exit(130); });
process.on("SIGTERM", () => { restore(); process.exit(143); });

try {
	for (const { file, filled } of configs) fs.writeFileSync(file, filled);
	for (const file of slateConfigs) {
		fs.writeFileSync(file, `/* Generated by scripts/deploy.js from .env - do not commit. */\nwindow.SPIKRA_CONFIG = { apiBase: ${JSON.stringify(env.API_BASE_URL)} };\n`);
	}
	const only = process.argv.includes("--only") ? process.argv[process.argv.indexOf("--only") + 1] : "functions,apig,slate";
	const result = spawnSync("catalyst", ["deploy", "--only", only], { cwd: ROOT, stdio: "inherit" });
	process.exitCode = result.status || 0;
} finally {
	restore();
	console.log("Config files restored to their committed (value-free) state.");
}
